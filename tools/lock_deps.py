"""Write exact, tested dependency pins from the current environment.

    python tools/lock_deps.py          # writes backend/requirements.lock and backend/requirements-dev.lock

Walks the requirement tree of the `orca-dispatch` package (runtime, then the dev / video
extras) through the installed distributions and pins every package to the version that
is installed here, i.e. the versions the test suite last passed with. Platform markers on
requirements (for example colorama on Windows) are carried over so the lock installs on
Linux CI and in Docker too. Install with:

    pip install -r backend/requirements.lock            # runtime (server, data, training)
    pip install -r backend/requirements-dev.lock        # + tests, lint, video tooling
"""
from __future__ import annotations

import re
import sys
from importlib import metadata
from pathlib import Path

import tomllib
from packaging.markers import Marker
from packaging.requirements import Requirement

ROOT = Path(__file__).resolve().parents[1]
PYPROJECT = ROOT / "backend" / "pyproject.toml"


def norm(name: str) -> str:
    return re.sub(r"[-_.]+", "-", name).lower()


def walk(roots: list[Requirement], extras_env: set[str] | None = None) -> dict[str, tuple[str, str | None]]:
    """name -> (version, marker that gated it, if any)."""
    out: dict[str, tuple[str, str | None]] = {}
    stack = [(r, None) for r in roots]
    while stack:
        req, inherited = stack.pop()
        marker = str(req.marker) if req.marker and "extra" not in str(req.marker) else inherited
        if req.marker and "extra" not in str(req.marker) and not req.marker.evaluate():
            # not needed on this platform, but keep the pin if we know a version for it
            pass
        key = norm(req.name)
        try:
            dist = metadata.distribution(req.name)
        except metadata.PackageNotFoundError:
            if marker:      # e.g. a Linux-only dependency we cannot resolve on Windows
                continue
            sys.exit(f"{req.name} is required but not installed; install it, run the tests, then re-lock")
        if key in out:
            # reachable unconditionally through another path wins over a marker-gated path
            if out[key][1] and not marker:
                out[key] = (dist.version, None)
            continue
        out[key] = (dist.version, marker)
        wanted = set(req.extras)
        for sub in dist.requires or []:
            r = Requirement(sub)
            if r.marker:
                m = str(r.marker)
                if "extra" in m:
                    if not any(Marker(m).evaluate({"extra": e}) for e in wanted):
                        continue
                    r.marker = None
                elif not r.marker.evaluate():
                    # platform-specific: pin only if it happens to be installed, keep its marker
                    try:
                        metadata.distribution(r.name)
                    except metadata.PackageNotFoundError:
                        continue
            stack.append((r, marker))
    return out


def write(path: Path, pins: dict[str, tuple[str, str | None]], title: str):
    lines = [f"# {title}", "# Generated by tools/lock_deps.py from the environment the tests passed in. Do not edit by hand.", ""]
    for name in sorted(pins):
        ver, marker = pins[name]
        lines.append(f"{name}=={ver}" + (f" ; {marker}" if marker else ""))
    path.write_text("\n".join(lines) + "\n")
    print(f"wrote {path.relative_to(ROOT)} ({len(pins)} packages)")


def main():
    proj = tomllib.loads(PYPROJECT.read_text())["project"]
    runtime = [Requirement(r) for r in proj["dependencies"]]
    extras = proj.get("optional-dependencies", {})
    dev = runtime + [Requirement(r) for k in ("dev", "video", "lint") for r in extras.get(k, [])]
    rt = walk(runtime)
    write(ROOT / "backend" / "requirements.lock", rt, "Runtime dependencies of the ORCA backend (server, data, training)")
    write(ROOT / "backend" / "requirements-dev.lock", walk(dev), "Runtime + development dependencies (tests, lint, tour video)")


if __name__ == "__main__":
    main()
