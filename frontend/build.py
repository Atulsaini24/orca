"""Bundle the control room: one self-contained index.html, plus per-city data loaded at start-up.

    python frontend/build.py           # writes frontend/index.html and frontend/data/<city>/config.js

The page's code is inlined. Each city's data (streets, buildings, trips: generated by
backend/scripts/*.py into frontend/data/<city>/) is loaded on demand for the chosen city only, from
/app/data/ when served or data/ next to the page when opened as a file. This writes each city's
config.js: its calibrated street speed, tuned scoring weights and model report, so the browser
engine decides exactly like the server for that city.
"""
import json
import pathlib
import sys

here = pathlib.Path(__file__).parent
root = here.parent
art = root / "backend" / "artifacts"
docs = root / "docs"
sys.path.insert(0, str(root / "backend"))
from orca import cityspec  # noqa: E402

order = ["sim.js", "cities.js", "gl.js", "city.js", "app.js"]
js = "\n".join((here / "src" / f).read_text(encoding="utf-8") for f in order)


def load(p: pathlib.Path):
    return json.loads(p.read_text()) if p.exists() else None


cities = []
for name, spec in cityspec.CITIES.items():
    d = here / "data" / name
    if not (d / "streets.js").exists():
        continue
    traffic = load(art / f"traffic_{name}.json") or (load(art / "nyc_traffic_profile.json") if name == "manhattan" else None)
    cal = load(art / f"speed_calibration_{name}.json") or {"speed_scale": 1.0}
    day = sum(traffic["speed_mps"][8:20]) / 12 if traffic else 3.8
    tuned = (load(art / f"dispatch_params_{name}.json") or {}).get("params", {})
    report = {"eta": load(art / f"eta_metrics_{name}.json"), "demand_tlc": load(art / f"demand_tlc_metrics_{name}.json"),
              "benchmark": load(docs / f"benchmark_{name}.json"), "city": name}
    (d / "config.js").write_text(
        "// Generated by frontend/build.py. Do not edit.\n"
        f"var CAL_MPS = {day / cal['speed_scale']:.5f};\n"
        f"var CITY_TUNED = {json.dumps(tuned)};\n"
        f"var CITY_REPORT = {json.dumps(report, separators=(',', ':'))};\n", encoding="utf-8")
    cities.append(dict(name=name, label=spec.label, short=spec.short, zones=spec.zone_label))

loader = """window.ORCA_CITIES = %s;
window.ORCA_LOAD = (async () => {
  const qs = new URLSearchParams(location.search), http = /^https?:$/.test(location.protocol);
  let city = qs.get('city');
  if (!city && http && !qs.has('capture') && location.hash !== '#demo') {
    try {
      const c = new AbortController(); const t = setTimeout(() => c.abort(), 1500);
      const h = await (await fetch('/api/health', { signal: c.signal, cache: 'no-store' })).json(); clearTimeout(t);
      city = h && h.city;
    } catch (e) { /* no server: run in the browser */ }
  }
  if (city !== 'grid' && !ORCA_CITIES.some((c) => c.name === city)) city = ORCA_CITIES.length ? ORCA_CITIES[0].name : 'grid';
  window.ORCA_CITY = city;
  if (city === 'grid') return;
  const base = (http ? '/app/data/' : 'data/') + city + '/';
  const one = (f) => new Promise((done) => { const s = document.createElement('script'); s.src = base + f + '.js'; s.onload = done; s.onerror = done; document.head.appendChild(s); });
  await Promise.all(['streets', 'buildings', 'trips', 'config'].map(one));
})();""" % json.dumps(cities)

html = (here / "src/index.html").read_text(encoding="utf-8")
html = html.replace("<script>window.ORCA_REPORT = /*__REPORT__*/null;</script>", f"<script>\n{loader}\n</script>")
html = html.replace("/*__APP__*/", "await window.ORCA_LOAD;\nwindow.ORCA_REPORT = typeof CITY_REPORT !== 'undefined' ? CITY_REPORT : null;\n" + js)
(here / "index.html").write_text(html, encoding="utf-8")
(root / "build-test").mkdir(exist_ok=True)
(root / "build-test" / "bundle.mjs").write_text(js, encoding="utf-8")
print(f"built frontend/index.html ({len(html) / 1024:.0f} KB) for {', '.join(c['short'] for c in cities) or 'the grid only'}")
