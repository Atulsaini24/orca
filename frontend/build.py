"""Bundle src/ into one self-contained index.html: no external code, only the web font.

    python frontend/build.py           # writes frontend/index.html

Data files (real streets, buildings and trips) are generated by backend/scripts/*.py and are
optional: without them the page falls back to the synthetic grid city.
"""
import json
import pathlib

here = pathlib.Path(__file__).parent
root = here.parent
art = root / "backend" / "artifacts"
order = ["buildings_data.js", "streets_data.js", "tlc_data.js", "sim.js", "cities.js", "gl.js", "city.js", "app.js"]
js = "\n".join((here / "src" / f).read_text(encoding="utf-8") for f in order if (here / "src" / f).exists())

# Calibrated street speed, identical to the Python engine's: real daytime median taxi speed / fitted scale.
try:
    day = sum(json.loads((art / "nyc_traffic_profile.json").read_text())["speed_mps"][8:20]) / 12
    cal = art / "speed_calibration_manhattan.json"
    scale = json.loads(cal.read_text())["speed_scale"] if cal.exists() else 1.0
    js = f"const CAL_MPS = {day / scale:.5f};\n" + js
except (OSError, KeyError, ValueError):
    pass


# Scoring weights tuned for the street city (python -m orca.tune), so the browser engine decides like the server.
tuned = art / "dispatch_params_manhattan.json"
if tuned.exists():
    w = json.loads(tuned.read_text())["params"]
    js = js.replace("function makeCity() {", "Object.assign(CFG, " + json.dumps(w) + ");   // tuned weights (orca.tune)\nfunction makeCity() {", 1)


def load(*names):
    """First artifact that exists: the Manhattan version, else the grid one."""
    for n in names:
        p = root / n
        if p.exists():
            return json.loads(p.read_text())
    return None


report = {
    "eta": load("backend/artifacts/eta_metrics_manhattan.json", "backend/artifacts/eta_metrics.json"),
    "demand": load("backend/artifacts/demand_sim_metrics_manhattan.json", "backend/artifacts/demand_sim_metrics.json"),
    "demand_tlc": load("backend/artifacts/demand_tlc_metrics_manhattan.json", "backend/artifacts/demand_tlc_metrics.json"),
    "benchmark": load("docs/benchmark.json"),
}
html = (here / "src/index.html").read_text(encoding="utf-8")
html = html.replace("/*__REPORT__*/null", json.dumps(report, separators=(",", ":")))
html = html.replace("/*__APP__*/", js)
(here / "index.html").write_text(html, encoding="utf-8")
(root / "build-test").mkdir(exist_ok=True)
(root / "build-test" / "bundle.mjs").write_text(js, encoding="utf-8")
print(f"built frontend/index.html ({len(html) / 1024:.0f} KB)")
